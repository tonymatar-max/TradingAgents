# Shared by install_services.ps1 and toggle_bot.ps1 (dot-source it). Builds and switches the Svc-<name> tasks.
#
# bots.json        : the tested instrument list (in git)
# bots.local.json  : THIS machine's choices (not in git):
#   { "enabled": {"GBPUSD": false, ...},          on/off per bot (overrides bots.json)
#     "extra":   [ {name, symbol, sl_atr, tp_atr, magic, logdir}, ... ],   instruments added from the portal
#     "live": true, "python": "C:\\...\\python.exe" }                        written by install_services.ps1
$Root = Split-Path -Parent $PSScriptRoot
$BotsFile = Join-Path $Root "bots.json"
$LocalFile = Join-Path $Root "bots.local.json"

function Read-Local {
    $l = @{ enabled = @{}; extra = @(); live = $null; python = $null }
    if (Test-Path $LocalFile) {
        $j = Get-Content $LocalFile -Raw | ConvertFrom-Json
        foreach ($p in $j.PSObject.Properties) {
            switch ($p.Name) {
                "enabled" { $p.Value.PSObject.Properties | ForEach-Object { $l.enabled[$_.Name] = [bool]$_.Value } }
                "extra"   { $l.extra = @($p.Value) }
                "live"    { $l.live = [bool]$p.Value }
                "python"  { $l.python = [string]$p.Value }
                default   { if ($p.Value -is [bool]) { $l.enabled[$p.Name] = $p.Value } }   # old flat format {"NVDA": false}
            }
        }
    }
    return $l
}

function Save-Local($l) {
    [ordered]@{ enabled = $l.enabled; extra = @($l.extra); live = $l.live; python = $l.python } |
        ConvertTo-Json -Depth 5 | Set-Content -Encoding UTF8 $LocalFile
}

function Get-Bots($l) {
    $cfg = Get-Content $BotsFile -Raw | ConvertFrom-Json
    $all = @($cfg.bots) + @($l.extra | ForEach-Object { $_ | Add-Member -NotePropertyName enabled -NotePropertyValue $true -Force -PassThru |
                                                           Add-Member -NotePropertyName evidence -NotePropertyValue "added by you, not backtested" -Force -PassThru })
    foreach ($b in $all) {
        $on = if ($l.enabled.ContainsKey($b.name)) { $l.enabled[$b.name] } else { [bool]$b.enabled }
        $b | Add-Member -NotePropertyName on -NotePropertyValue $on -Force
    }
    return @{ threshold = $cfg.threshold; risk = $cfg.risk; bots = $all }
}

function Write-Launcher($name, $logdir, $cmd) {
    $run = Join-Path $Root "scripts\services"
    New-Item -ItemType Directory -Force $run | Out-Null
    $file = Join-Path $run "run_$($name.ToLower()).ps1"
    @"
# Auto-generated by svc_common.ps1
Set-Location "$Root"
New-Item -ItemType Directory -Force "$logdir" | Out-Null
while (`$true) {
    $cmd 2>> "$logdir\crash.log"
    Add-Content "$logdir\crash.log" ("{0}  $name exited, restarting in 30 s" -f (Get-Date -Format "yyyy-MM-dd HH:mm:ss"))
    Start-Sleep -Seconds 30
}
"@ | Set-Content -Encoding UTF8 $file
    return $file
}

function Register-Svc($name, $launcher, $enabled, $delay) {
    $user = "$env:USERDOMAIN\$env:USERNAME"
    $principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive
    $settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
        -ExecutionTimeLimit ([TimeSpan]::Zero) -MultipleInstances IgnoreNew -RestartCount 99 -RestartInterval (New-TimeSpan -Minutes 1)
    $trigger = New-ScheduledTaskTrigger -AtLogOn -User $user
    if ($delay) { $trigger.Delay = "PT1M" }     # give MT5 a minute to log in
    Register-ScheduledTask -TaskName "Svc-$name" -Principal $principal -Settings $settings -Trigger $trigger -Force `
        -Action (New-ScheduledTaskAction -Execute "powershell.exe" -WorkingDirectory $Root `
            -Argument "-NoProfile -ExecutionPolicy Bypass -WindowStyle Minimized -File `"$launcher`"") | Out-Null
    Set-SvcState $name $enabled
}

function Set-SvcState($name, $enabled) {
    $task = "Svc-$name"
    if ($enabled) {
        Enable-ScheduledTask -TaskName $task | Out-Null
        if ((Get-ScheduledTask -TaskName $task).State -ne "Running") { Start-ScheduledTask -TaskName $task }
    } else {
        Stop-ScheduledTask -TaskName $task -ErrorAction SilentlyContinue
        Disable-ScheduledTask -TaskName $task | Out-Null
    }
}

function Install-Bot($b, $cfg, $py, $live) {
    $logdir = Join-Path $Root $b.logdir
    $flags = "--symbol $($b.symbol) --timeframe H1 --threshold $($cfg.threshold) --sl-atr $($b.sl_atr) --tp-atr $($b.tp_atr) " +
             "--risk $($cfg.risk) --magic $($b.magic) --logdir `"$logdir`" --log-file `"$logdir\bot.log`"" + $(if ($live) { " --live-orders" } else { "" })
    $launcher = Write-Launcher $b.name $logdir "& `"$py`" -m xauusd_agents mt5 $flags"
    Register-Svc $b.name $launcher $b.on $true
}
